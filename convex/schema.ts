import { defineSchema, defineTable } from 'convex/server';
import { v } from 'convex/values';
const id = v.string(),
  money = v.number(),
  scope = v.union(v.literal('CAS'), v.literal('KET'), v.literal('COUPLE')),
  slug = v.union(v.literal('CAS'), v.literal('KET'));
const optionalId = v.optional(id);
export default defineSchema({
  users: defineTable({
    id,
    slug,
    name: v.string(),
    email: v.string(),
    passwordHash: v.string(),
    encryptedPluggyCredentials: v.optional(v.string()),
  })
    .index('by_slug', ['slug'])
    .index('by_email', ['email']),
  accounts: defineTable({
    id,
    ownerScope: scope,
    name: v.string(),
    institution: v.string(),
    type: v.string(),
    balanceCents: money,
    externalId: optionalId,
    archived: v.boolean(),
    bankBalanceCents: v.optional(v.number()),
    bankBalanceAt: v.optional(v.number()),
  }).index('by_owner', ['ownerScope']),
  cards: defineTable({
    id,
    ownerScope: scope,
    name: v.string(),
    last4: v.string(),
    limitCents: money,
    closingDay: v.number(),
    dueDay: v.number(),
    cashbackBps: v.number(),
    archived: v.boolean(),
  }).index('by_owner', ['ownerScope']),
  categories: defineTable({
    id,
    code: v.string(),
    name: v.string(),
    iconName: v.string(),
    type: v.string(),
    isEssential: v.boolean(),
  }),
  categoryRules: defineTable({
    id,
    ownerScope: scope,
    merchantPattern: v.string(),
    categoryId: id,
    defaultOwnerScope: scope,
    matchCount: v.number(),
  }).index('by_owner', ['ownerScope']),
  transactions: defineTable({
    id,
    ownerScope: scope,
    paidByUserId: slug,
    accountId: optionalId,
    cardId: optionalId,
    destinationAccountId: optionalId,
    categoryId: id,
    type: v.string(),
    status: v.string(),
    amountCents: money,
    cashbackEarnedCents: money,
    description: v.string(),
    merchantNormalized: v.string(),
    occurredAt: v.string(),
    dueDate: v.optional(v.string()),
    coupleSplit: v.optional(
      v.object({
        casShareBps: v.number(),
        ketShareBps: v.number(),
        casAmountCents: money,
        ketAmountCents: money,
        settled: v.boolean(),
      }),
    ),
    externalId: optionalId,
    sourceAccountKey: optionalId,
    source: v.string(),
    installmentGroup: optionalId,
    installmentNumber: v.optional(v.number()),
    installmentTotal: v.optional(v.number()),
    entryKind: v.string(),
    relatedId: optionalId,
    invoiceMonth: v.optional(v.string()),
    createdBy: slug,
    createdAt: v.number(),
  })
    .index('by_owner_date', ['ownerScope', 'occurredAt'])
    .index('by_external', ['accountId', 'source', 'externalId']),
  budgets: defineTable({
    id,
    ownerScope: scope,
    categoryId: id,
    monthKey: v.string(),
    limitCents: money,
  }).index('by_owner_month', ['ownerScope', 'monthKey']),
  investments: defineTable({
    id,
    ownerScope: scope,
    name: v.string(),
    type: v.string(),
    principalCents: money,
    currentBalanceCents: money,
    cdiPercentageBps: v.number(),
    hasFgcProtection: v.boolean(),
    valuationDate: v.string(),
  }).index('by_owner', ['ownerScope']),
  agentAlerts: defineTable({
    id,
    agentId: v.string(),
    targetScope: scope,
    severity: v.string(),
    title: v.string(),
    message: v.string(),
    relatedTransactionId: optionalId,
    dismissed: v.boolean(),
    period: v.string(),
  }),
  auditLogs: defineTable({
    id,
    actorSlug: slug,
    action: v.string(),
    metadataSanitized: v.object({ entityId: optionalId, result: v.string() }),
    createdAt: v.number(),
  }),
  goals: defineTable({
    id,
    ownerScope: scope,
    name: v.string(),
    targetCents: money,
    savedCents: money,
    targetDate: v.string(),
  }),
  recurringBills: defineTable({
    id,
    ownerScope: scope,
    name: v.string(),
    amountCents: money,
    dueDay: v.number(),
    categoryId: id,
    active: v.boolean(),
  }),
  settlements: defineTable({
    id,
    monthKey: v.string(),
    from: slug,
    to: slug,
    amountCents: money,
    paidAt: v.string(),
    createdBy: slug,
  }),
  bankConnections: defineTable({
    id,
    userSlug: slug,
    itemIds: v.array(v.string()),
    lastSyncAt: v.optional(v.number()),
    provider: v.string(),
  }),
  sessions: defineTable({
    id,
    userSlug: slug,
    tokenHash: v.string(),
    expiresAt: v.number(),
    createdAt: v.number(),
  }).index('by_session_id', ['id']),
  loginThrottles: defineTable({ id, failures: v.number(), resetAt: v.number() }),
});
